df.columns

df.drop(columns=[
    'Customer Email',
    'Customer Password',
    'Customer Street',
    'Latitude',
    'Longitude',
    'Order Zipcode',
    'Order Customer Id',
    'Benefit per order',
    'Sales per customer',
    'Order Item Product Price',
    'Order Item Cardprod Id',
    'Product Description',
    'Product Image',
    'Product Status',
    'Product Category Id'
], inplace=True ,errors='ignore')

df.head()

df.columns

df['Customer Lname']=df['Customer Fname'].fillna('Uk')

df['Customer Zipcode']=df['Customer Zipcode'].fillna(0)

df.isnull().sum()

"""**------------------------------------Discover Outlier--------------------------------**


"""

df.describe()

columns = [
    "Sales",
    "Order Item Discount",
    "Order Profit Per Order",
    "Order Item Total",
    'Product Price'


]

for col in columns:
    if col in df.columns:
        plt.figure(figsize=(8, 3))
        sns.boxplot(x=df[col])
        plt.title(f"Boxplot of {col}")
        plt.show()

for col in columns:
    if col in df.columns:
        Q1 = df[col].quantile(0.25)
        Q3 = df[col].quantile(0.75)
        IQR = Q3 - Q1

        lower = Q1 - 1.5 * IQR
        upper = Q3 + 1.5 * IQR

        count = (
            (df[col] < lower) |
            (df[col] > upper)
        ).sum()

        print(f"{col}: {count} outliers")

for col in columns:
    Q1 = df[col].quantile(0.25)
    Q3 = df[col].quantile(0.75)
    IQR = Q3 - Q1

    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR

    print(f"\nColumn: {col}")
    print("Q1:", Q1)
    print("Q3:", Q3)
    print("IQR:", IQR)

    print("Min:", df[col].min())
    print("Max:", df[col].max())
    print("Lower Bound:", lower)
    print("Upper Bound:", upper)

    print("Lowest values:")
    print(df.loc[df[col] < lower, col].sort_values().head(5).tolist())

    print("Highest values:")
    print(df.loc[df[col] > upper, col].sort_values(ascending=False).head(5).tolist())

df.to_csv('/content/DataCoSupplyChain_Cleaned.csv', index=False)

